"""Rank the B-series members refit with the exact cascade (reassessment 2026-11-20).

  bseries_rank.py --emit-reeval   print queue lines: each member's best f_dep + REFRC_f0.5
  bseries_rank.py                 write runs/BS_rank/table.csv and README.md

Best f_dep per member = highest held-out lnL (n_seed 3000). The ranking uses the
n_seed 8000 re-evaluation (keys 11/202/3003) where present, else the held-out mean.
Laplace lnZ is taken at the n_seed 3000 MAP and shifted by (lnL_8000 - lnL_fit),
i.e. the same Occam factor on the better lnL estimate. References are REFRC_f0.5.
"""
import argparse, glob, json, os, shutil
import numpy as np

WS = os.path.expanduser("~/20261120-hier-reassess")
SCAN = os.path.join(WS, "runs/BS_scan")
OUT = os.path.join(WS, "runs/BS_rank")
MEMBERS = ["NULL", "BB", "BC", "BD", "BMIX", "NULLG", "REFRC"]
LABEL = {"NULL": "null", "BB": "B_b", "BC": "B_c", "BD": "B_d", "BMIX": "Bmix",
         "NULLG": "null + g(eta) exch 0", "REFRC": "combined (REFRC)"}
# paper tab:bseries, committed proposal (macros_results.tex, model_ranking etafix_k10_vesc1000)
PAPER = {"NULL": (-36.5, -34.4), "BB": (-12.5, -12.8), "BC": (-40.3, -38.5),
         "BD": (-19.3, -21.3), "BMIX": (-37.7, -34.3), "REFRC": (0.0, 0.0), "NULLG": (None, None)}
PAPER_FDEP = {"NULL": 0.9, "BB": 0.9, "BC": 0.9, "BD": 0.9, "BMIX": 0.9, "REFRC": 0.7, "NULLG": None}


def load():
    res = {}
    for f in glob.glob(os.path.join(SCAN, "*/result.json")):
        r = json.load(open(f)); tag = os.path.basename(os.path.dirname(f))
        r["tag"] = tag
        rf = os.path.join(os.path.dirname(f), "reeval_n8000.json")
        r["reeval"] = json.load(open(rf)) if os.path.exists(rf) else None
        res.setdefault(r["model"], []).append(r)
    return res


def ensure_refrc():
    d = os.path.join(SCAN, "REFRC_f0.5")
    if not os.path.exists(os.path.join(d, "result.json")):
        os.makedirs(d, exist_ok=True)
        shutil.copy(os.path.join(WS, "runs/B_scan/REFRC_f0.5/result.json"), d)


def best(rs):
    return max(rs, key=lambda r: r["lnL_heldout_mean"])


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--emit-reeval", action="store_true")
    a = ap.parse_args()
    ensure_refrc()
    res = load()
    if a.emit_reeval:
        for m in MEMBERS:
            if m in res:
                print(best(res[m])["tag"])
        return
    rows = []
    for m in MEMBERS:
        if m not in res:
            continue
        b = best(res[m])
        scan = {r["f_dep"]: (r["lnL_heldout_mean"], r["lnL_heldout_sd"]) for r in res[m]}
        if b["reeval"]:
            L, sd, src = b["reeval"]["lnL_mean"], b["reeval"]["lnL_sd"], "n8000"
        else:
            L, sd, src = b["lnL_heldout_mean"], b["lnL_heldout_sd"], "heldout_n3000"
        lnZ = b["lnZ_laplace_bdy"] - b["lnL"] + L
        rows.append(dict(member=m, label=LABEL[m], best_f_dep=b["f_dep"], lnL=L, lnL_sd=sd, lnL_src=src,
                         lnZ=lnZ, railing=";".join(b["railing"]) if b.get("railing") else "",
                         negH_pd=b["negH_pd"], n_par=len(b["names"]),
                         scan=" ".join(f"{f}:{v[0]:.1f}" for f, v in sorted(scan.items())),
                         theta=b["theta_map"], paper_dlnL=PAPER[m][0], paper_dlnZ=PAPER[m][1],
                         paper_f_dep=PAPER_FDEP[m]))
    ref = next((r for r in rows if r["member"] == "REFRC"), None)
    for r in rows:
        r["dlnL"] = r["lnL"] - ref["lnL"] if ref else None
        r["dlnZ"] = r["lnZ"] - ref["lnZ"] if ref else None
    os.makedirs(OUT, exist_ok=True)
    cols = ["member", "label", "best_f_dep", "lnL", "lnL_sd", "lnL_src", "lnZ", "dlnL", "dlnZ",
            "paper_dlnL", "paper_dlnZ", "paper_f_dep", "n_par", "negH_pd", "railing", "scan"]
    with open(os.path.join(OUT, "table.csv"), "w") as f:
        f.write(",".join(cols) + ",theta_map\n")
        for r in rows:
            f.write(",".join("" if r[c] is None else (f"{r[c]:.2f}" if isinstance(r[c], float) else str(r[c]))
                             for c in cols) + ',"' + json.dumps({k: round(v, 4) for k, v in r["theta"].items()}).replace('"', "'") + '"\n')
    rk_new = sorted(rows, key=lambda r: -r["dlnZ"])
    rk_old = sorted([r for r in rows if r["paper_dlnZ"] is not None], key=lambda r: -r["paper_dlnZ"])
    lines = ["# B-series refit with the exact cascade", "",
             "Generated by `engine-bseries/demo/inference/bseries_rank.py`. Each member is",
             "refit by MAP + Laplace with every cascade proposal equal to its target",
             "(`hier_map_laplace.py`, f_dep in {0.5, 0.7, 0.9}). lnL at the best f_dep is the",
             "n_seed 8000 / n_b 6000 mean over keys 11, 202, 3003 where available. Laplace lnZ",
             "keeps the n_seed 3000 Occam factor. Differences are relative to REFRC (combined).",
             "Paper columns are tab:bseries (committed proposal, posterior mean, 10 keys).", "",
             "| member | best f_dep | lnL (sd) | dlnL | dlnZ | paper dlnL | paper dlnZ | rails |",
             "|---|---|---|---|---|---|---|---|"]
    for r in rk_new:
        lines.append(f"| {r['label']} | {r['best_f_dep']} | {r['lnL']:.1f} ({(r['lnL_sd'] or float('nan')):.1f}, {r['lnL_src']}) | "
                     f"{r['dlnL']:+.1f} | {r['dlnZ']:+.1f} | "
                     f"{'' if r['paper_dlnL'] is None else r['paper_dlnL']} | {'' if r['paper_dlnZ'] is None else r['paper_dlnZ']} | {r['railing']} |")
    lines += ["", "Rank by dlnZ, exact: " + " > ".join(r["label"] for r in rk_new),
              "Rank by dlnZ, paper: " + " > ".join(r["label"] for r in rk_old), "",
              "Held-out lnL (n_seed 3000) by f_dep:", ""]
    lines += [f"- {r['label']}: {r['scan']}" for r in rows]
    open(os.path.join(OUT, "README.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
