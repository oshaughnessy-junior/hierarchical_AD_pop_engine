"""Collect the workstream-B MAP/Laplace scan into table.csv + README.md.

Re-runnable while jobs land: finished fits come from <tag>/result.json, running
ones are listed from <tag>/state.npz, and n_seed-8000 re-evaluations from
<tag>/reeval_n8000.json.

Reference row: dlnL is against the REF fit with the highest held-out lnL; dlnZ
against the REF fit with the highest lnZ_heldout (each REF at its best f_dep).

  python hier_postprocess.py --scan runs/B_scan               # table + README
  python hier_postprocess.py --scan runs/B_scan --emit-reeval 3   # job lines
"""
import argparse, csv, glob, json, os
import numpy as np

PARAMS = ["mu_A", "sig_A", "m_max_A", "spin_chi", "mu_B", "sig_B", "f_peakB",
          "alpha_B", "mu_chiB", "sig_chiB", "log_R_A", "log_R_B"]


def load(scan):
    rows, running = [], []
    for d in sorted(glob.glob(os.path.join(scan, "*/"))):
        tag = os.path.basename(d.rstrip("/"))
        f = os.path.join(d, "result.json")
        if os.path.exists(f):
            r = json.load(open(f)); r["tag"] = tag
            fr = os.path.join(d, "reeval_n8000.json")
            if os.path.exists(fr):
                e = json.load(open(fr))
                r["lnL_8k_mean"] = e["lnL_mean"]; r["lnL_8k_sd"] = e["lnL_sd"]
                r["lnL_8k_keys"] = " ".join(f"{x['key']}:{x['lnL']:.1f}" for x in e["evals"])
            rows.append(r)
        elif os.path.exists(os.path.join(d, "state.npz")):
            s = np.load(os.path.join(d, "state.npz"), allow_pickle=True)
            running.append((tag, str(s["phase"]), int(s["step"]), float(s["best_L"])))
        elif os.path.exists(os.path.join(d, ".failed_fit")):
            running.append((tag, "FAILED", 0, float("nan")))
    return rows, running


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--scan", required=True)
    p.add_argument("--emit-reeval", type=int, default=0)
    a = p.parse_args()
    rows, running = load(a.scan)
    if a.emit_reeval:
        # top-N by lnZ_bdy, plus the best REF so the 8k comparison has a reference
        srt = sorted(rows, key=lambda r: -r["lnZ_heldout"])
        pick = [r["tag"] for r in srt[:a.emit_reeval]]
        refs = [r for r in srt if r["model"] == "REF"]
        if refs and refs[0]["tag"] not in pick:
            pick.append(refs[0]["tag"])
        print("\n".join(pick))
        return 0
    refs = [r for r in rows if r["model"] == "REF"]
    refL = max((r["lnL_heldout_mean"] for r in refs), default=None)
    refZ = max((r["lnZ_heldout"] for r in refs), default=None)
    cols = ["tag", "model", "start", "f_dep", "lnL_fitkey", "lnL_heldout", "lnL_heldout_sd",
            "dlnL_vs_REF", "lnZ_laplace", "lnZ_laplace_bdy", "lnZ_heldout", "dlnZ_vs_REF", "negH_pd", "railing", "field_frac_det",
            "mu_det", "lnL_8k_mean", "lnL_8k_sd", "lnL_8k_keys"] + PARAMS
    out = []
    for r in sorted(rows, key=lambda r: (r["model"], r["f_dep"], r["tag"])):
        o = dict(tag=r["tag"], model=r["model"], start=r.get("start", ""), f_dep=r["f_dep"],
                 lnL_fitkey=round(r["lnL"], 2), lnL_heldout=round(r["lnL_heldout_mean"], 2),
                 lnL_heldout_sd=round(r["lnL_heldout_sd"], 2) if r.get("lnL_heldout_sd") else "",
                 dlnL_vs_REF="" if refL is None else round(r["lnL_heldout_mean"] - refL, 2),
                 lnZ_laplace=round(r["lnZ_laplace"], 2),
                 lnZ_laplace_bdy=round(r["lnZ_laplace_bdy"], 2),
                 lnZ_heldout=round(r["lnZ_heldout"], 2),
                 dlnZ_vs_REF="" if refZ is None else round(r["lnZ_heldout"] - refZ, 2),
                 negH_pd=r["negH_pd"], railing=";".join(r["railing"]),
                 field_frac_det=round(r["field_frac_det"], 3), mu_det=round(r["mu"], 1),
                 lnL_8k_mean=round(r["lnL_8k_mean"], 2) if "lnL_8k_mean" in r else "",
                 lnL_8k_sd=round(r["lnL_8k_sd"], 2) if r.get("lnL_8k_sd") is not None else "",
                 lnL_8k_keys=r.get("lnL_8k_keys", ""))
        for k in PARAMS:
            o[k] = round(r["theta_map"][k], 4) if k in r["theta_map"] else ""
        out.append(o)
    with open(os.path.join(a.scan, "table.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols); w.writeheader(); w.writerows(out)

    md = ["# Workstream B: fully hierarchical models, MAP + Laplace scan", "",
          "Generated by `engine-hier/demo/inference/hier_postprocess.py`; re-run it as jobs land.",
          "", "Catalog `full_o3_o4a_o4b_catalog_NAL_exNSBH_etafix.npz` (236 events, 3D NAL, full cov), "
          "selection `mass_pdet_grid_kappa2.7.npz`, v_esc 1000, exchange mode 0, g(eta) kernel lor "
          "eta0 0.23 w 0.03, n_seed 3000 / n_b 3000, cascade key 11. Fits: "
          "`hier_map_laplace.py --mode fit` (Adam on the rate-profiled lnL, then L-BFGS-B, "
          "then the exact Hessian).", "",
          "Models: REF = headline (flat-PL natal, free m_max_A, channel-B mixture field); "
          "H0 = Gaussian-seeded cascade, no field; H1 = H0 + broad aligned PL field on [5,80] "
          "(slope `alpha_B`); H2 = H0 + aligned field sharing (mu_A, sig_A). Field spins and "
          "rate reuse the channel-B names (`mu_chiB`, `sig_chiB`, `log_R_B`).", "",
          "lnL_fitkey is lnL at the MAP on the cascade key the fit optimized (optimistic); "
          "lnL_heldout is the mean (sd) over three fresh keys at the same n_seed, and is the "
          "number to compare. Every model except REF moves its natal proposal onto the "
          "target at the optimum (recentred), because the cascade weights a merger by "
          "0.5(w_i+w_j); REFRC is REF with that recentring. "
          "dlnL = lnL_heldout vs the best REF; dlnZ = lnZ_heldout (Laplace with the "
          "boundary correction, lnL replaced by lnL_heldout) vs the best REF. "
          "lnZ_bdy subtracts ln 2 per parameter within 1% of a prior edge (listed in "
          "`railing`); lnZ_laplace does not. `negH_pd` False means the Hessian is not "
          "negative definite and the Laplace number is not usable. `field_frac_det` = "
          "fraction of expected detections from the field (channel B). lnL_8k = mean "
          "(sd) over sampler keys 11, 202, 3003 at n_seed 8000 / n_b 6000, at the n_seed-3000 MAP.",
          "", "| tag | f_dep | lnL fit key | lnL held-out (sd) | dlnL | lnZ held-out | dlnZ | H pd | railing | field det frac | "
          "lnL 8k (sd) | key params |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for o in out:
        kp = " ".join(f"{k}={o[k]}" for k in PARAMS if o[k] != "" and not k.startswith("log_R"))
        l8 = f"{o['lnL_8k_mean']} ({o['lnL_8k_sd']})" if o["lnL_8k_mean"] != "" else ""
        md.append(f"| {o['tag']} | {o['f_dep']} | {o['lnL_fitkey']} | {o['lnL_heldout']} ({o['lnL_heldout_sd']}) | "
                  f"{o['dlnL_vs_REF']} | {o['lnZ_heldout']} | {o['dlnZ_vs_REF']} | {o['negH_pd']} | "
                  f"{o['railing']} | {o['field_frac_det']} | {l8} | {kp} |")
    if running:
        md += ["", "Not finished (tag, phase, step, best lnL so far; Adam reports the rate-profiled lnL):", ""]
        md += [f"- {t}: {ph} step {st} best {bl:.2f}" for t, ph, st, bl in running]
    open(os.path.join(a.scan, "README.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
